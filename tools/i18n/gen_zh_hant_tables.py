"""Generate the Simplified -> Traditional (Hong Kong / Taiwan) conversion data the app reads at run time.

Input:  a folder holding OpenCC's dictionaries (Apache-2.0): STCharacters.txt, STPhrases.txt,
        HKVariants.txt, TWVariants.txt. They ship inside the PyPI package
        opencc-python-reimplemented==0.1.7 (opencc/dictionary/), or in https://github.com/BYVoid/OpenCC.
Output: app/src/main/resources/zh_hant/zh_hant.tsv (read by ChineseScript.kt).

Run from the repo root (no installs needed, standard library only):
    python3 -I tools/i18n/gen_zh_hant_tables.py <opencc-dictionary-folder> app/src/main/resources/zh_hant/zh_hant.tsv

What it builds, following OpenCC's own chains (s2hk = ST phrases, ST characters, HKVariants; s2tw = ST phrases,
ST characters, TWVariants). Not s2twp: the Taiwan WORDING list (TWPhrases: 软件 -> 軟體) would change what a
caller said in a transcript, so only the character forms are taken for Taiwan.
  c <simplified> <hk> <tw>    one character, only where the answer differs from the character itself
  p <simplified> <hk> <tw>    one phrase, only where the answer differs from converting it character by
                              character (that is what a phrase is for: 发 = 發 or 髮, 干 = 幹 or 乾 ...)
A "=" in the tw column means "the same as hk". Phrases are capped at MAX_PHRASE characters to keep the file small.
"""
import sys

MAX_PHRASE = 5
# Characters whose phrases are always kept, even when they equal the per-character answer: the app's Cantonese
# mode reads 系 as 係 ("is") everywhere EXCEPT in these words, so the words must stay in the table.
ALWAYS_KEEP = "系"
# Hand fixes on top of OpenCC, per variant. Hong Kong writes 麵 (as 麵包), where OpenCC's HK variants leave 麪.
HK_FIXES = {"麪": "麵"}
TW_FIXES = {}


def read(path):
    out = {}
    with open(path, encoding="utf-8") as handle:
        for line in handle:
            line = line.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            key, values = line.split("\t")
            out[key] = values.split(" ")[0]  # OpenCC lists the preferred form first
    return out


def main(dicts, target):
    st_chars = read(f"{dicts}/STCharacters.txt")
    st_phrases = read(f"{dicts}/STPhrases.txt")
    hk_var = read(f"{dicts}/HKVariants.txt")
    tw_var = read(f"{dicts}/TWVariants.txt")

    def char_to(variants, fixes):
        def convert(ch):
            ch = st_chars.get(ch, ch)
            ch = variants.get(ch, ch)
            return fixes.get(ch, ch)
        return convert

    hk = char_to(hk_var, HK_FIXES)
    tw = char_to(tw_var, TW_FIXES)

    def phrase_to(variants, fixes):
        def convert(word):
            return "".join(fixes.get(variants.get(c, c), variants.get(c, c)) for c in word)
        return convert

    hk_phrase = phrase_to(hk_var, HK_FIXES)
    tw_phrase = phrase_to(tw_var, TW_FIXES)

    rows = []
    chars = sorted(set(st_chars) | set(hk_var) | set(tw_var))
    kept_chars = 0
    for ch in chars:
        h, t = hk(ch), tw(ch)
        if len(h) != 1 or len(t) != 1:
            continue
        if ord(ch) > 0xFFFF or ord(h) > 0xFFFF or ord(t) > 0xFFFF:
            continue  # the app reads characters as single UTF-16 units; these rare ones are two
        if h == ch and t == ch:
            continue
        rows.append(("c", ch, h, t))
        kept_chars += 1

    kept_phrases = 0
    for word, value in st_phrases.items():
        if len(word) < 2 or len(word) > MAX_PHRASE or len(value) != len(word):
            continue
        h, t = hk_phrase(value), tw_phrase(value)
        h_plain = "".join(hk(c) for c in word)
        t_plain = "".join(tw(c) for c in word)
        if h == h_plain and t == t_plain and not any(c in ALWAYS_KEEP for c in word):
            continue
        rows.append(("p", word, h, t))
        kept_phrases += 1

    rows.sort(key=lambda r: (r[0], r[1]))
    with open(target, "w", encoding="utf-8", newline="\n") as out:
        out.write("# Generated by tools/i18n/gen_zh_hant_tables.py from OpenCC dictionaries (Apache-2.0).\n")
        out.write("# See NOTICE.md. Columns: kind, simplified, Hong Kong, Taiwan ('=' = same as Hong Kong).\n")
        for kind, source, h, t in rows:
            out.write(f"{kind}\t{source}\t{h}\t{'=' if t == h else t}\n")
    print(f"characters: {kept_chars}, phrases: {kept_phrases}, file: {target}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
