package com.baba.callvault.transcription

import androidx.appcompat.app.AppCompatDelegate
import com.baba.callvault.utils.AppLogger
import java.util.Locale

/**
 * Simplified → Traditional Chinese for transcripts and summaries (BabApps items 117 and 125).
 *
 * Whisper writes Chinese in Simplified characters most of the time. Readers on Hong Kong and Taiwan phones
 * expect Traditional, so the finished text is converted. It is a plain lookup: the same text always gives the
 * same result, and Latin letters, digits and text that is already Traditional are left alone.
 *
 * The data is OpenCC's (Apache-2.0, see NOTICE.md): `s2hk` for Hong Kong and `s2tw` for Taiwan, generated by
 * `tools/i18n/gen_zh_hant_tables.py` into `zh_hant/zh_hant.tsv`. The character table covers every Simplified
 * character OpenCC knows; the phrase list holds only the words where a character has several Traditional
 * forms (发 = 發 or 髮), so the answer follows the word. Taiwan gets the character forms only, not OpenCC's
 * Taiwan wording list: converting what a caller said into other words is not this file's job.
 *
 * **zh-CN is never converted** — [variantFor] returns null for it.
 */
object ChineseScript {

    enum class Variant { HK, TW }

    /**
     * What to do for one transcript or summary.
     *
     * @param cantonese Cantonese reads 系 as 係 ("is") except in the words the table lists, and writes 甚麼.
     */
    data class Conversion(val variant: Variant, val cantonese: Boolean = false)

    /**
     * The Traditional variant for a phone or app [locale], or null when it is not a Traditional-Chinese one.
     * zh-HK, zh-MO and zh-Hant-HK/MO give Hong Kong; zh-TW and a bare zh-Hant give Taiwan; zh, zh-CN, zh-SG and
     * anything with the Hans script give null.
     */
    fun variantFor(locale: Locale): Variant? {
        if (!locale.language.equals("zh", ignoreCase = true)) return null
        if (locale.script.equals("Hans", ignoreCase = true)) return null
        return when {
            locale.country.uppercase(Locale.ROOT) in HK_REGIONS -> Variant.HK
            locale.country.equals("TW", ignoreCase = true) -> Variant.TW
            locale.script.equals("Hant", ignoreCase = true) -> Variant.TW
            else -> null
        }
    }

    /**
     * The conversion for a transcript pinned to [language], on a phone or app set to [locale]; null leaves the
     * text as it came. Pinned Cantonese is always Hong Kong Traditional; pinned Chinese follows the locale.
     */
    fun forTranscript(language: String?, locale: Locale): Conversion? = when (language) {
        "yue" -> Conversion(Variant.HK, cantonese = true)
        "zh" -> variantFor(locale)?.let { Conversion(it) }
        else -> null
    }

    /**
     * The conversion for a summary written in [language]: "yue", or "zh-HK" / "zh-TW" (what
     * [summaryLanguage] gives). Anything else is null.
     */
    fun forSummary(language: String?): Conversion? = when (language?.lowercase(Locale.ROOT)) {
        "yue" -> Conversion(Variant.HK, cantonese = true)
        "zh-hk" -> Conversion(Variant.HK)
        "zh-tw" -> Conversion(Variant.TW)
        else -> null
    }

    /** "zh" on a Hong Kong or Taiwan phone becomes "zh-HK" or "zh-TW", so the summary prompt can ask for Traditional. */
    fun summaryLanguage(language: String, locale: Locale): String =
        if (language == "zh") when (variantFor(locale)) {
            Variant.HK -> "zh-HK"
            Variant.TW -> "zh-TW"
            null -> language
        } else language

    /** The language the user sees the app in: the app's own choice when set, otherwise the phone's. */
    fun effectiveLocale(): Locale =
        runCatching { AppCompatDelegate.getApplicationLocales().takeIf { !it.isEmpty }?.get(0) }.getOrNull()
            ?: Locale.getDefault()

    fun convert(text: String, conversion: Conversion?): String {
        if (conversion == null) return text
        // A table that cannot load must never fail a transcription: the text then comes back as it was.
        // The failure is logged once, by the table's own loader.
        val data = try {
            Tables
        } catch (t: Throwable) {
            return text
        }
        var changed = false
        val out = StringBuilder(text.length)
        var i = 0
        while (i < text.length) {
            if (text[i] < '⺀') { // Latin, digits, punctuation: never in the tables
                out.append(text[i])
                i++
                continue
            }
            val phrase = data.phraseAt(text, i, conversion.variant)
            if (phrase != null) {
                out.append(phrase.second)
                i += phrase.first
                changed = true
            } else {
                val ch = text[i]
                val mapped = if (conversion.cantonese && ch == '系') '係' else data.char(ch, conversion.variant)
                if (mapped != ch) changed = true
                out.append(mapped)
                i++
            }
        }
        if (!changed) return text
        val result = out.toString()
        return if (conversion.cantonese) result.replace("什麼", "甚麼") else result
    }

    fun convert(segment: TranscriptSegment, conversion: Conversion?): TranscriptSegment =
        if (conversion == null) segment
        else segment.copy(
            text = convert(segment.text, conversion),
            parts = segment.parts.map { convert(it, conversion) },
        )

    private val HK_REGIONS = setOf("HK", "MO")

    /** The generated data, read once on first use. */
    private object Tables {
        private val hkChars = HashMap<Char, Char>(8192)
        private val twChars = HashMap<Char, Char>(8192)
        private val hkPhrases = HashMap<String, String>(16384)
        private val twPhrases = HashMap<String, String>(16384)
        private var longest = 2

        init {
            try {
                load()
                note("zh_hant table loaded: ${hkChars.size} chars, ${hkPhrases.size} phrases (HK/TW)")
            } catch (e: Throwable) {
                // Logged because the conversion would otherwise fail only when the first Chinese call is transcribed.
                note("zh_hant table FAILED to load: $e", failed = true)
                throw e
            }
        }

        val summary: String get() = "${hkChars.size} chars, ${hkPhrases.size} phrases (HK/TW)"

        /** Always on (not gated by the debug-log switch): this is what proves the file is in the APK and readable. */
        private fun note(message: String, failed: Boolean = false) {
            runCatching { if (failed) AppLogger.e(TAG, message) else AppLogger.i(TAG, message) }
        }

        private fun load() {
            val stream = ChineseScript::class.java.classLoader!!.getResourceAsStream(RESOURCE)
                ?: error("Missing resource $RESOURCE")
            stream.bufferedReader(Charsets.UTF_8).useLines { lines ->
                for (line in lines) {
                    if (line.isEmpty() || line[0] == '#') continue
                    val cols = line.split('\t')
                    if (cols.size != 4) continue
                    val tw = if (cols[3] == "=") cols[2] else cols[3]
                    if (cols[0] == "c") {
                        // A rare character outside the Basic Multilingual Plane is two Kotlin chars; skipped.
                        if (cols[1].length != 1 || cols[2].length != 1 || tw.length != 1) continue
                        hkChars[cols[1][0]] = cols[2][0]
                        twChars[cols[1][0]] = tw[0]
                    } else {
                        hkPhrases[cols[1]] = cols[2]
                        twPhrases[cols[1]] = tw
                        if (cols[1].length > longest) longest = cols[1].length
                    }
                }
            }
        }

        fun char(ch: Char, variant: Variant): Char =
            (if (variant == Variant.HK) hkChars else twChars)[ch] ?: ch

        /** The longest phrase starting at [at]: its length and its Traditional form. */
        fun phraseAt(text: String, at: Int, variant: Variant): Pair<Int, String>? {
            val map = if (variant == Variant.HK) hkPhrases else twPhrases
            for (len in minOf(longest, text.length - at) downTo 2) {
                val found = map[text.substring(at, at + len)]
                if (found != null) return len to found
            }
            return null
        }
    }

    /** What the conversion table holds, loading it if needed; for the debug report. Never throws. */
    fun tableSummary(): String = runCatching { Tables.summary }.getOrElse { "failed to load: $it" }

    private const val TAG = "CV:ChineseScript"
    private const val RESOURCE = "zh_hant/zh_hant.tsv"
}
